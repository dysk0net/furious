#!/usr/bin/env python3
"""Turns an Airwindows VST plug-in (the WinVST sources) into a self-contained C++ class without any VST SDK.

    python3 Tools/port_airwindows.py kRockstar2 Weave

Downloads <Name>.h, <Name>.cpp and <Name>Proc.cpp from github.com/airwindows/airwindows and writes
Source/Dsp/Airwindows/<Name>.h with class stratum::aw::<Name>:  reset(), setSampleRate(), setParam(i, 0..1 value),
process(L, R, frames) (in place, stereo) and paramName(i).  The processing code is Airwindows' own, unchanged
(MIT licence, see Source/Dsp/Airwindows/LICENSE-airwindows.txt).
"""
import os, re, sys, urllib.request

BASE = "https://raw.githubusercontent.com/airwindows/airwindows/master/plugins/WinVST/{n}/{f}"
OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "Source", "Dsp", "Airwindows")

def get(n, f):
    with urllib.request.urlopen(BASE.format(n=n, f=f), timeout=30) as r:
        return r.read().decode("utf-8", "replace")

def port(name):
    h, c, p = get(name, name + ".h"), get(name, name + ".cpp"), get(name, name + "Proc.cpp")
    # constants declared before the class (delay lengths, tables ...), without the VST plumbing
    pre = h[h.index("kNumParameters"):h.index("class " + name)]
    pre = pre.split("}; //", 1)[1] if "}; //" in pre else pre.split("};", 1)[1]
    pre = "\n".join(l for l in pre.splitlines() if not re.search(r"kNumPrograms|kNumInputs|kNumOutputs|kUniqueId", l))
    # data members
    body = h[h.index("std::set< std::string > _canDo;") + len("std::set< std::string > _canDo;"):h.rindex("};")]
    # the parameter list
    nparam = len(re.findall(r"kParam[A-Z]\s*=", h))
    names = re.findall(r'case kParam[A-Z]: vst_strncpy \(text, "([^"]*)"', c.split("getParameterName")[1].split("getParameterDisplay")[0])
    # constructor body
    m = re.search(name + r"::" + name + r"\(audioMasterCallback audioMaster\)\s*:\s*AudioEffectX\([^)]*\)\s*\{(.*?)\n\}", c, re.S)
    ctor = "\n".join(l for l in m.group(1).splitlines() if not re.search(r"_canDo|_programName|canDo|setNumInputs|setNumOutputs|setUniqueID|canProcessReplacing|programsAreChunks|vst_strncpy|DECLARE_VST_DEPRECATED|isSynth|noTail|setInitialDelay", l))
    # float processing loop
    a = p.index("void " + name + "::processReplacing")
    b = p.index("void " + name + "::processDoubleReplacing")
    seg = p[a:b]
    seg = seg[seg.index("{") + 1:seg.rindex("}")]
    seg = "\n".join(l for l in seg.splitlines() if not re.match(r"\s*float\*\s*(in|out)[12]\s*=", l))
    seg = seg.replace("getSampleRate()", "sampleRate").replace("sampleFrames", "sampleFrames")
    letters = "ABCDEFGHIJKLMNOP"[:nparam]
    sets = "\n".join("            case %d: %s = v; break;" % (i, ch) for i, ch in enumerate(letters))
    nm = "\n".join('            case %d: return "%s";' % (i, n) for i, n in enumerate(names))
    out = f'''#pragma once
// Generated by Tools/port_airwindows.py from Airwindows' {name} (MIT licence, Copyright (c) 2018 Chris Johnson,
// see LICENSE-airwindows.txt). The processing code below is theirs, unchanged apart from removing the VST wrapper.
#include <cmath>
#include <cstdint>
#include <cstdlib>
#include <algorithm>
// MSVC only defines the M_ constants with _USE_MATH_DEFINES
#ifndef M_PI
#define M_PI 3.14159265358979323846
#endif
#ifndef M_PI_2
#define M_PI_2 1.57079632679489661923
#endif
#ifndef M_PI_4
#define M_PI_4 0.78539816339744830962
#endif

namespace stratum {{ namespace aw {{
namespace {name}Impl {{
typedef int32_t VstInt32;
namespace {name}Data {{
{pre}
}}
using namespace {name}Data;

class {name}
{{
public:
    static constexpr int kNumParams = {nparam};
    static const char* paramName (int i)
    {{
        switch (i)
        {{
{nm}
            default: return "";
        }}
    }}
    {name}() {{ reset(); }}
    void setSampleRate (double sr) {{ sampleRate = sr > 1000.0 ? sr : 44100.0; }}
    void setParam (int i, float v)
    {{
        switch (i)
        {{
{sets}
            default: break;
        }}
    }}
    // Puts every delay line and filter back to silence (also resets the parameters to Airwindows' defaults).
    void reset()
    {{
{ctor}
    }}
    // Processes in place.
    void process (float* io1, float* io2, int sampleFrames)
    {{
        float* in1 = io1; float* in2 = io2; float* out1 = io1; float* out2 = io2;
{seg}
    }}

private:
    double sampleRate = 44100.0;
{body}}};
}}   // namespace {name}Impl (keeps this effect's constants from clashing with the others')
using {name}Impl::{name};
}} }} // namespace stratum::aw
'''
    os.makedirs(OUT, exist_ok=True)
    path = os.path.join(OUT, name + ".h")
    open(path, "w").write(out)
    print("wrote", os.path.normpath(path), "params:", names)

if __name__ == "__main__":
    for n in sys.argv[1:]:
        port(n)
    lic = os.path.join(OUT, "LICENSE-airwindows.txt")
    if not os.path.exists(lic):
        with urllib.request.urlopen("https://raw.githubusercontent.com/airwindows/airwindows/master/LICENSE", timeout=30) as r:
            open(lic, "w").write(r.read().decode())
